// Builds 00 Start Here/Index.md from the vault's Markdown files.
// Usage: node "A:/roblox game/game/tools/build-index.mjs"
import fs from "node:fs";
import path from "node:path";

const root = "A:/roblox game";
const outFile = path.join(root, "00 Start Here", "Index.md");
const skipDirs = new Set([".obsidian", "attachments", "game"]);

function walk(dir, rel = "") {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const childRel = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (skipDirs.has(entry.name)) continue;
      files.push(...walk(path.join(dir, entry.name), childRel));
    } else if (entry.name.endsWith(".md")) {
      files.push(childRel);
    }
  }
  return files;
}

const files = walk(root)
  .filter((f) => f !== "00 Start Here/Index.md")
  .sort((a, b) => a.localeCompare(b));

const byTop = new Map();
for (const file of files) {
  const parts = file.split("/");
  const top = parts[0];
  if (!byTop.has(top)) byTop.set(top, []);
  byTop.get(top).push(parts.slice(1).join("/"));
}

const order = [
  "00 Start Here",
  "01 Game Design",
  "02 Story",
  "03 Systems",
  "04 Scenarios",
  "05 World",
  "06 Development",
  "07 Player Wiki",
  "08 Research",
  "09 Templates",
];

function link(rel) {
  const name = path.basename(rel, ".md");
  const full = `${rel}`.replace(/\\/g, "/").replace(/\.md$/, "");
  return `- [[${full}|${name}]]`;
}

function renderFolder(top) {
  const rels = byTop.get(top) ?? [];
  const direct = rels.filter((r) => !r.includes("/"));
  const subdirs = new Map();
  for (const rel of rels.filter((r) => r.includes("/"))) {
    const [sub, ...rest] = rel.split("/");
    if (!subdirs.has(sub)) subdirs.set(sub, []);
    subdirs.get(sub).push(rest.join("/"));
  }

  let text = `## ${top}\n\n`;
  if (direct.length) {
    text += direct.map((r) => link(`${top}/${r}`)).join("\n") + "\n\n";
  }
  for (const [sub, subRels] of [...subdirs.entries()].sort()) {
    text += `### ${sub}\n\n`;
    text += subRels
      .sort()
      .map((r) => link(`${top}/${sub}/${r}`))
      .join("\n") + "\n\n";
  }
  return text;
}

